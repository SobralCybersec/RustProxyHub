function lookup(tree: MessageTree | string | string[] | undefined, path: string): unknown {
  if (!tree || typeof tree === 'string' || Array.isArray(tree)) return tree
  return path.split('.').reduce<unknown>((current, segment) => {
    if (!current || typeof current !== 'object' || Array.isArray(current)) return undefined
    return (current as MessageTree)[segment]
  }, tree)
}

export function messageAt(locale: UiLocale, path: string): unknown {
  return lookup(messages[locale] ?? messages[DEFAULT_LOCALE], path) ?? lookup(messages[DEFAULT_LOCALE], path)
}

export function translate(
  locale: UiLocale,
  path: string,
  params: Record<string, string | number> = {},
): string {
  const value = messageAt(locale, path)
  if (typeof value !== 'string') return path
  return value.replace(/\{(\w+)\}/g, (_, token) => String(params[token] ?? ''))
}

export function localeTimeCode(locale: UiLocale): string {
  return locale === 'en' ? 'en-US' : 'pt-BR'
}

